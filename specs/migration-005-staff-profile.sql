-- <STEP1-ADDRESS-BEGIN>
-- ----------------------------------------------------------------------------
-- STEP 1a — users.address (địa chỉ, optional, max 255 ở tầng app).
-- TEXT NULL thuần, KHÔNG CHECK length ở DB (giữ nhất quán với phone/notes và
